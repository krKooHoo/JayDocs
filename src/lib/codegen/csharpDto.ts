/**
 * 표(TSV · CSV) → C# DTO 클래스 (DESIGN §26). 순수 함수만 둔다 — 파일 접근은 App 이 한다.
 *
 * DTO 는 "표의 거울"이다: 머리글 이름 = 필드 이름(글자 그대로), 함수 없음. 필드 자료형은 셋뿐이다(Jay 2026-11-20).
 *   int    — 정수
 *   float  — 실수
 *   string — 그 밖의 전부 (enum 값 · 경로 · 매크로 · T/F …). 해석은 Def 를 만드는 쪽이 한다
 *
 * 행을 읽는 규칙은 게임 쪽 리더(CsvHelper, `#` 로 시작하는 줄은 주석)와 같게 맞췄다:
 *   - 첫 칸이 `#` 로 시작하는 줄은 주석. 다만 1행이 `#타입` 꼴이면 타입 행으로 읽는다
 *   - 주석 · 빈 줄을 건너뛴 뒤 첫 줄이 머리글, 그 아래의 주석 · 빈 줄이 아닌 줄이 데이터
 * 그래서 JayDocs 계약(1행 타입, 2행 머리글) · 머리글만 있는 표 · `#타입 / #설명 / 머리글` 3행 표가 모두 같은 규칙으로 읽힌다.
 */
import { COLUMN_TYPES } from '../tsv/schema'

/** 생성 파일의 표식. 이 글자가 있는 파일만 묻지 않고 덮어쓴다 */
export const DTO_MARKER = '<auto-generated>'

export type DtoFieldType = 'int' | 'float' | 'string'

export interface DtoField {
  column: number
  /** 머리글 그대로 */
  header: string
  /** C# 에 쓰는 이름 — 예약어면 `@` 를 붙인다 (멤버 이름은 그대로라 머리글과 맞는다) */
  name: string
  type: DtoFieldType
  /** declared: 타입 행에 적힌 대로 · inferred: 데이터를 보고 정했다 */
  typeSource: 'declared' | 'inferred'
  summary: string | null
}

/**
 * 필드로 만들지 않은 열.
 * comment: 머리글이 `#` 로 시작(주석 열) · empty: 머리글이 빔 — 이 둘은 알리지 않는다.
 * untyped: 타입 행의 칸이 빔(JayDocs 계약의 주석 열) · invalid: C# 이름으로 쓸 수 없음 · duplicate: 앞 열과 같은 이름
 */
export type DtoSkipReason = 'comment' | 'empty' | 'untyped' | 'invalid' | 'duplicate'
export interface DtoSkip {
  column: number
  header: string
  reason: DtoSkipReason
}

export interface DtoModel {
  /** 머리글 행의 번호(0부터). 못 찾으면 null */
  headerRow: number | null
  /** 1행을 타입 행으로 읽었나 */
  typed: boolean
  /** 타입을 정할 때 본 데이터 행 수 */
  dataRows: number
  fields: DtoField[]
  skipped: DtoSkip[]
}

/** 타입 행에서 int · float 로 받는 이름들. 나머지는 전부 string */
const INT_TYPES = new Set(['int', 'byte', 'uint', 'short', 'ushort', 'sbyte'])
const FLOAT_TYPES = new Set(['float', 'double'])
/** 타입 행의 첫 칸으로 알아보는 이름들 (`#string`, `#int` …) */
const FIRST_TYPES = new Set<string>([...COLUMN_TYPES, ...INT_TYPES, ...FLOAT_TYPES, 'long', 'ulong'])
const TYPE_WORD = /^[A-Za-z_][A-Za-z0-9_]*$/
const INT_VALUE = /^[+-]?\d+$/
const FLOAT_VALUE = /^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/
const INT_MIN = -2147483648
const INT_MAX = 2147483647

/** C# 예약어 (문맥 키워드는 이름으로 쓸 수 있어 뺐다) */
const CS_KEYWORDS = new Set((
  'abstract as base bool break byte case catch char checked class const continue decimal default delegate do double else enum event '
  + 'explicit extern false finally fixed float for foreach goto if implicit in int interface internal is lock long namespace new null '
  + 'object operator out override params private protected public readonly ref return sbyte sealed short sizeof stackalloc static '
  + 'string struct switch this throw true try typeof uint ulong unchecked unsafe ushort using virtual void volatile while'
).split(' '))

const CS_IDENT = /^[\p{L}\p{Nl}_][\p{L}\p{Nl}\p{Mn}\p{Mc}\p{Nd}\p{Pc}]*$/u

/** C# 식별자로 쓸 수 있는 글자들인가 (한글도 된다). 예약어 여부는 따로 본다 */
export function isCsIdentifier(name: string): boolean {
  return CS_IDENT.test(name)
}

export function isCsKeyword(name: string): boolean {
  return CS_KEYWORDS.has(name)
}

function isBlank(cells: readonly string[]) {
  return cells.every((c) => c.trim() === '')
}
function isComment(cells: readonly string[]) {
  return (cells[0] ?? '').startsWith('#')
}

/** 1행이 타입 행인가: 첫 칸이 `#` + 아는 타입 이름이고, 나머지 비지 않은 칸이 전부 낱말 하나 */
function isTypeRow(cells: readonly string[]): boolean {
  const first = (cells[0] ?? '').trim()
  if (!first.startsWith('#') || !FIRST_TYPES.has(first.slice(1).trim().toLowerCase())) return false
  for (let c = 1; c < cells.length; c++) {
    const v = cells[c].trim()
    if (v !== '' && !TYPE_WORD.test(v)) return false
  }
  return true
}

/**
 * 열의 데이터 칸들 → 자료형 (타입 행이 없을 때).
 * 모든 칸이 int 범위의 정수면 int, 모든 칸이 숫자이고 소수점 · 지수가 든 칸이 하나라도 있으면 float, 그 밖에는 string.
 * 빈 칸이 하나라도 있거나 데이터가 없으면 string — 리더는 숫자 열의 빈 칸에서 그 행을 버린다.
 * int 범위를 넘는 정수만 있는 열도 string 이다 (float 로 받으면 자릿수를 잃는다).
 */
function inferType(values: readonly string[]): DtoFieldType {
  if (values.length === 0) return 'string'
  let allInt = true
  for (const raw of values) {
    const s = raw.trim()
    if (INT_VALUE.test(s)) {
      const n = Number(s)
      if (n < INT_MIN || n > INT_MAX) return 'string'
    } else if (FLOAT_VALUE.test(s) && Number.isFinite(Number(s))) allInt = false
    else return 'string'
  }
  return allInt ? 'int' : 'float'
}

/**
 * 표의 칸들 → DTO 의 필드 목록.
 * describe: 열 설명을 줄 수 있으면 (Field 시트). 없으면 머리글 바로 위의 주석 행(`#설명` 행)을 쓴다.
 */
export function analyzeDto(rows: readonly (readonly string[])[], describe?: (header: string, column: number) => string | null): DtoModel {
  const typed = rows.length > 0 && isTypeRow(rows[0])
  const typeRow = typed ? rows[0] : null
  let headerRow: number | null = null
  for (let r = typed ? 1 : 0; r < rows.length; r++) {
    if (isComment(rows[r]) || isBlank(rows[r])) continue
    headerRow = r
    break
  }
  if (headerRow === null) return { headerRow: null, typed, dataRows: 0, fields: [], skipped: [] }

  // 타입 행과 머리글 사이에 주석 행이 있으면 (3행 표의 `#설명`) 머리글 바로 위의 것을 설명으로 쓴다
  let noteRow: readonly string[] | null = null
  for (let r = headerRow - 1; r >= (typed ? 1 : 0); r--) {
    if (isComment(rows[r])) { noteRow = rows[r]; break }
  }
  const data: (readonly string[])[] = []
  for (let r = headerRow + 1; r < rows.length; r++) {
    if (!isComment(rows[r]) && !isBlank(rows[r])) data.push(rows[r])
  }

  const head = rows[headerRow]
  const fields: DtoField[] = []
  const skipped: DtoSkip[] = []
  const taken = new Set<string>()
  for (let c = 0; c < head.length; c++) {
    const header = head[c]
    const skip = (reason: DtoSkipReason) => skipped.push({ column: c, header, reason })
    if (header.trim() === '') { skip('empty'); continue }
    if (header.trim().startsWith('#')) { skip('comment'); continue }
    let declared: string | null = null
    if (typeRow) {
      declared = (typeRow[c] ?? '').trim().toLowerCase()
      if (c === 0) declared = declared.replace(/^#\s*/, '')
      if (declared === '') { skip('untyped'); continue }
    }
    // 리더는 머리글을 글자 그대로 맞춘다 — 앞뒤 공백이 있으면 필드와 이어지지 않으니 고치게 알린다
    if (!isCsIdentifier(header)) { skip('invalid'); continue }
    if (taken.has(header)) { skip('duplicate'); continue }
    taken.add(header)

    let type: DtoFieldType
    if (declared !== null) type = INT_TYPES.has(declared) ? 'int' : FLOAT_TYPES.has(declared) ? 'float' : 'string'
    else type = inferType(data.map((row) => row[c] ?? ''))

    let summary = describe?.(header, c)?.trim() || null
    if (!summary && noteRow) {
      let note = (noteRow[c] ?? '').trim()
      if (c === 0) note = note.replace(/^#\s*/, '')
      summary = note || null
    }
    fields.push({ column: c, header, name: isCsKeyword(header) ? `@${header}` : header, type, typeSource: declared !== null ? 'declared' : 'inferred', summary })
  }
  return { headerRow, typed, dataRows: data.length, fields, skipped }
}

const SKIP_TEXT: Record<DtoSkipReason, string> = {
  comment: '주석 열',
  empty: '머리글이 비어 있음',
  untyped: '타입 행의 칸이 비어 있음 (주석 열)',
  invalid: 'C# 이름으로 쓸 수 없음',
  duplicate: '앞 열과 이름이 같음',
}

/** 알릴 만한 건너뛴 열 (`#` 주석 열 · 빈 머리글은 뺀다) — `"My Col" — C# 이름으로 쓸 수 없음` */
export function dtoSkipNotes(model: DtoModel): string[] {
  return model.skipped
    .filter((s) => s.reason !== 'comment' && s.reason !== 'empty')
    .map((s) => `"${s.header}" — ${SKIP_TEXT[s.reason]}`)
}

function xmlText(s: string): string {
  return s.replace(/\s*[\r\n]+\s*/g, ' ').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}
/** 줄 주석 안에 넣을 글 — 줄바꿈만 없앤다 */
function oneLine(s: string): string {
  return s.replace(/\s*[\r\n]+\s*/g, ' ')
}

export interface DtoRenderOptions {
  className: string
  /** 표 파일 이름 (경로 없이) — 머리 주석에 적는다 */
  source: string
  eol?: '\n' | '\r\n'
}

/**
 * C# 소스. 같은 표면 늘 같은 글이 나온다(날짜를 넣지 않는다) — 바뀐 것이 없으면 파일을 다시 쓰지 않아 Unity 가 다시 컴파일하지 않는다.
 */
export function renderDto(model: DtoModel, o: DtoRenderOptions): string {
  const lines = [
    `// ${DTO_MARKER}`,
    `// JayDocs 가 ${oneLine(o.source)} 의 머리글에서 만든 파일입니다.`,
    '// 직접 고치지 마세요 — 표를 고친 뒤 다시 내보내면 덮어씁니다.',
  ]
  const notes = dtoSkipNotes(model)
  if (notes.length) {
    lines.push('//', '// 필드로 만들지 않은 열:')
    for (const n of notes) lines.push(`//   ${oneLine(n)}`)
  }
  lines.push('// </auto-generated>', '', `/// <summary>${xmlText(o.source)} 의 한 행.</summary>`, `public class ${o.className}`, '{')
  for (const f of model.fields) {
    if (f.summary) lines.push(`    /// <summary>${xmlText(f.summary)}</summary>`)
    lines.push(`    public ${f.type} ${f.name};`)
  }
  lines.push('}', '')
  return lines.join(o.eol ?? '\n')
}

/** JayDocs 가 만든 파일인가 (앞부분에 표식이 있다) */
export function hasDtoMarker(text: string): boolean {
  return text.slice(0, 400).includes(DTO_MARKER)
}

function baseName(path: string): string {
  return path.split('/').pop() ?? path
}
function stemOf(path: string): string {
  return baseName(path).replace(/\.[^.]+$/, '')
}

/** 영어 복수형을 단수로 — 흔한 꼴만 (enemies → enemy, units → unit). 아닌 것은 그대로 */
function singular(word: string): string {
  if (/[a-z]ies$/.test(word)) return word.slice(0, -3) + 'y'
  if (/(ss|us|is)$/.test(word)) return word
  if (word.length > 2 && /[a-z]s$/.test(word)) return word.slice(0, -1)
  return word
}

/**
 * 표 파일 이름 → 기본 클래스 이름. 대화상자에 미리 채우는 값일 뿐이고 사용자가 고칠 수 있다.
 * `Tile_Table.tsv` → `TileDTO` · `enemies.tsv` → `EnemyDTO` · `wave_meta.tsv` → `WaveMetaDTO`
 */
export function defaultDtoClassName(tablePath: string): string {
  const words = stemOf(tablePath).replace(/_Table$/i, '').split(/[^\p{L}\p{Nd}]+/u).filter(Boolean)
  if (words.length) words[words.length - 1] = singular(words[words.length - 1])
  let name = words.map((w) => w[0].toUpperCase() + w.slice(1)).join('')
  if (name === '') name = 'Table'
  if (/^\p{Nd}/u.test(name)) name = `_${name}`
  return `${name}DTO`
}

/** `.cs` 경로의 클래스 이름 (파일 이름에서 확장자를 뗀 것) */
export function dtoClassNameOf(csPath: string): string {
  return stemOf(csPath)
}

/** 내보낼 경로에 문제가 있으면 그 이유, 없으면 null. 경로의 글자 검사(금지 문자 · `..`)는 부르는 쪽이 `checkEntryPath` 로 한다 */
export function checkDtoPath(csPath: string): string | null {
  if (!/\.cs$/i.test(csPath)) return '.cs 로 끝나야 합니다'
  const name = dtoClassNameOf(csPath)
  if (name === '') return '확장자 앞에 클래스 이름이 있어야 합니다'
  if (!isCsIdentifier(name)) return `파일 이름이 클래스 이름이 됩니다 — "${name}" 은 C# 이름으로 쓸 수 없습니다 (글자 · 숫자 · _ 만, 숫자로 시작하지 않게)`
  if (isCsKeyword(name)) return `"${name}" 은 C# 예약어라 클래스 이름으로 쓸 수 없습니다`
  return null
}
